#!/usr/bin/env python3
"""Builds src/usda.js from the USDA FoodData Central CSV downloads (https://fdc.nal.usda.gov/download-datasets).

    python3 tools/usda_import.py path/to/sr_legacy_csv_dir path/to/foundation_csv_dir

Keeps calories, protein, carbs, fiber and fat per 100g for SR Legacy and Foundation foods, skipping
categories nobody logs here (baby food, branded and restaurant records, lab samples). A food gets a
piece size (so "2" logs two) only when USDA lists a one-piece portion like "1 medium" or "1 slice".
The raw downloads are large and public, so they are not kept in the repo.
"""
import csv, json, os, re, sys

SKIP_CATEGORIES = {'Baby Foods', 'Restaurant Foods', 'Branded Food Products Database',
                   'Quality Control Materials', 'American Indian/Alaska Native Foods'}
KCAL = ('1008', '2048', '2047')   # Energy, then Atwater specific, then Atwater general (Foundation often has only these)
PROTEIN, FAT, CARBS, CARBS_SUM, FIBER, FIBER_AOAC = '1003', '1004', '1005', '1050', '1079', '2033'
NEEDED = set(KCAL) | {PROTEIN, FAT, CARBS, CARBS_SUM, FIBER, FIBER_AOAC}
# One-piece portions worth counting. "medium" wins over "large" for produce; eggs already have a curated entry.
PIECE_WORDS = ['medium', 'large', 'small', 'slice', 'piece', 'patty', 'link', 'strip', 'fruit', 'egg', 'wing',
               'drumstick', 'thigh', 'breast', 'leg', 'chop', 'fillet', 'tortilla', 'bagel', 'muffin', 'cookie',
               'roll', 'bun', 'biscuit', 'pancake', 'waffle', 'bar', 'frank', 'sausage', 'shrimp', 'stalk', 'clove']

def rows(path):
    with open(path, newline='', encoding='utf-8') as f:
        yield from csv.DictReader(f)

def load(d, keep_ids=None):
    cats = {r['id']: r['description'] for r in rows(os.path.join(d, 'food_category.csv'))}
    foods = {}
    for r in rows(os.path.join(d, 'food.csv')):
        if keep_ids is not None and r['fdc_id'] not in keep_ids: continue
        if cats.get(r['food_category_id'], '') in SKIP_CATEGORIES: continue
        foods[r['fdc_id']] = {'n': r['description'].strip(), 'nut': {}, 'pc': None}
    for r in rows(os.path.join(d, 'food_nutrient.csv')):
        f = foods.get(r['fdc_id'])
        if f and r['nutrient_id'] in NEEDED and r['amount'] != '':
            f['nut'][r['nutrient_id']] = float(r['amount'])
    best = {}
    for r in rows(os.path.join(d, 'food_portion.csv')):
        f = foods.get(r['fdc_id'])
        if not f or r['amount'] not in ('1', '1.0'): continue
        text = (r.get('modifier') or '') + ' ' + (r.get('portion_description') or '')
        word = next((w for w in PIECE_WORDS if re.search(r'\b' + w + r's?\b', text.lower())), None)
        g = float(r['gram_weight'] or 0)
        if not word or not (0 < g <= 1000): continue
        rank = PIECE_WORDS.index(word)
        if r['fdc_id'] not in best or rank < best[r['fdc_id']]:
            best[r['fdc_id']] = rank; f['pc'] = [word, round(g, 1)]
    return foods

def row(f):
    n = f['nut']
    kcal = next((n[k] for k in KCAL if k in n), None)
    if kcal is None or PROTEIN not in n: return None
    carbs = max(0.0, n.get(CARBS, n.get(CARBS_SUM, 0.0)))  # 'by difference' can dip below 0 from rounding
    fiber = min(n.get(FIBER, n.get(FIBER_AOAC, 0.0)), carbs)  # missing fiber counts as 0, so net carbs read high, never low
    r = [f['n']] + [round(max(0.0, v), 1) for v in (kcal, n[PROTEIN], carbs, fiber, n.get(FAT, 0.0))]
    if f['pc']: r += f['pc']
    return r

def main(sr_dir, fd_dir, out_path, existing_names):
    fd_ids = {r['fdc_id'] for r in rows(os.path.join(fd_dir, 'foundation_food.csv'))}
    out, seen = [], {s.lower() for s in existing_names}
    # Foundation first: newer analyses win when the same description appears in both.
    for f in list(load(fd_dir, fd_ids).values()) + list(load(sr_dir).values()):
        r = row(f)
        if r and r[0].lower() not in seen:
            seen.add(r[0].lower()); out.append(r)
    out.sort(key=lambda r: r[0].lower())
    body = json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
    with open(out_path, 'w', encoding='utf-8') as fh:
        fh.write('// Generated by tools/usda_import.py from USDA FoodData Central (SR Legacy 2018-04, Foundation Foods). Do not edit by hand.\n')
        fh.write('  // Rows: [name, kcal, protein, carbs, fiber, fat, pieceName?, pieceGrams?] per 100g.\n')
        fh.write('  FOODS = FOODS.concat(' + body + '.map(function(r){ return F(r[0], "", r[1], r[2], r[3], r[4], r[5], r[6] ? [r[6], r[7]] : null); }));\n')
    print(f'wrote {len(out)} USDA foods to {out_path}')

if __name__ == '__main__':
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    names = re.findall(r"F\('((?:[^'\\]|\\.)*)'", open(os.path.join(root, 'src', 'foods.js'), encoding='utf-8').read())
    main(sys.argv[1], sys.argv[2], os.path.join(root, 'src', 'usda.js'), names)
